// Score 独立评分：同一份评分标准，由两个模型（或同模型不同温度）各评一次。
const Score = `给下面这条资料的热点价值打分（0-10，一位小数）。

评分标准：
- 9-10 分：整个行业都会关注。重大模型发布、重大开源项目爆发、里程碑论文、重大政策或安全事件。
- 7-8 分：生态内有广泛影响。新版本带来显著能力变化、值得关注的新玩家、有数据支撑的趋势报告。
- 5-6 分：值得从业者一看，但影响面有限。
- 3-4 分：例行更新、边缘话题。
- 0-2 分：几乎没有热点价值。

打分时保持独立判断，不要因为来源名气大就放水。

资料：
{{ITEM}}

输出 JSON：
{"score":0.0,"reason":"一句话中文评分理由"}`

